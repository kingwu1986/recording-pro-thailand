const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
for (const [, code] of scripts) new vm.Script(code);
const code = html.slice(html.indexOf('    function allGradeExportRows'), html.indexOf('    async function downloadAllGrades'));
const csvCode = html.slice(html.indexOf('    function csvCell'), html.indexOf('    function renderTeacherAccounts'));
const ctx = vm.createContext({});
vm.runInContext(code + csvCode, ctx);
const students = [{studentId:'a',name:'甲',active:true},{studentId:'b',name:'乙',active:false},{studentId:'c',name:'丙',active:true}];
const attempts = [100,0,80].map((score,i) => ({studentId:'a',setId:'same-homework',score,attemptId:String(i),assignmentTitle:'题目,"换行\n测试',passedCount:1,questionCount:2}));
attempts.push({studentId:'b',setId:'same-homework',score:85,attemptId:'b1'});
const sets = [{setId:'same-homework',published:true,includeInAverage:true},{setId:'unsubmitted',published:true,includeInAverage:true},{setId:'excluded',published:true,includeInAverage:false},{setId:'draft',published:false,includeInAverage:true}];
const rows = ctx.allGradeExportRows({students,attempts,sets});
assert.equal(rows.length, 8);
assert.equal(rows[1][3],2);
assert.equal(rows[1][4],100);
assert.equal(rows[1][5],'50.00');
assert.equal(rows[5][2],'停用');
assert.equal(rows[5][5],'42.50');
assert.equal(rows[7][3],2);
assert.equal(rows[7][5],'0.00');
assert.ok(rows.every(r => r.length === 14));
const excludedRows = ctx.allGradeExportRows({students:[students[0]],sets,attempts:[...attempts,{studentId:'a',setId:'excluded',score:100},{studentId:'a',setId:'draft',score:100}]});
assert.equal(excludedRows[1][5],'50.00');
assert.equal(excludedRows.at(-2)[13],'否');
assert.equal(ctx.allGradeExportRows({students,attempts,sets:[]})[1][5],'暂无计入作业');
assert.equal(ctx.allGradeExportRows({students,attempts,sets:sets.map(s=>({...s,includeInAverage:false}))})[1][5],'暂无计入作业');
assert.equal(ctx.csvCell('=SUM(A1)'), '"\'=SUM(A1)"');
assert.equal(ctx.csvCell('a,"b\nc'), '"a,""b\nc"');
const many = Array.from({length:1201},(_,i)=>({studentId:'a',setId:'same-homework',score:80,attemptId:String(i)}));
assert.equal(ctx.allGradeExportRows({students:[students[0]],attempts:many,sets})[1][3],2);
assert.equal(ctx.allGradeExportRows({students:[students[0]],attempts:many,sets})[1][5],'40.00');
console.log('Passed: published assignment denominator, missing homework=0, best repeat score, excluded/draft assignments, no included assignments, CSV escaping and >500 attempts.');
