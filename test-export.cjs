const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
for (const [, code] of scripts) new vm.Script(code);
const code = html.slice(html.indexOf('    function allGradeExportRows'), html.indexOf('    async function downloadAllGrades'));
const csvCode = html.slice(html.indexOf('    function csvCell'), html.indexOf('    function renderTeacherAccounts'));
const ctx = vm.createContext({});
vm.runInContext(code + csvCode, ctx);
const students = [{studentId:'a',name:'甲',active:true},{studentId:'b',name:'乙',active:false},{studentId:'c',name:'丙',active:true}];
const attempts = [100,0,80].map((score,i) => ({studentId:'a',setId:'same-homework',score,attemptId:String(i),assignmentTitle:'题目,"换行\n测试',passedCount:1,questionCount:2}));
attempts.push({studentId:'b',score:85,attemptId:'b1'});
const rows = ctx.allGradeExportRows({students,attempts});
assert.equal(rows.length, 8);
assert.equal(rows[1][3],3);
assert.equal(rows[1][4],180);
assert.equal(rows[1][5],'60.00');
assert.equal(rows[5][2],'停用');
assert.equal(rows[5][5],'85.00');
assert.equal(rows[7][3],0);
assert.equal(rows[7][5],'暂无成绩');
assert.ok(rows.every(r => r.length === 13));
assert.equal(ctx.csvCell('=SUM(A1)'), '"\'=SUM(A1)"');
assert.equal(ctx.csvCell('a,"b\nc'), '"a,""b\nc"');
const many = Array.from({length:1201},(_,i)=>({studentId:'a',score:80,attemptId:String(i)}));
assert.equal(ctx.allGradeExportRows({students:[students[0]],attempts:many})[1][3],1201);
console.log('Passed: script syntax, average, zero scores, repeated submissions, inactive/no-score students, CSV escaping, >500 attempts.');
